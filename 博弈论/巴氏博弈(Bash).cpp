// 给定n个石子
// 两个人轮流拿, 每次可以拿[1, m]个
// 拿走最后一个石子的人获胜
// 问: 先手和后手谁会赢

// n % (m + 1) != 0, 先手赢
// n % (m + 1) == 0, 后手赢

// 原理: 对于m + 1的整数倍(包括0)
// 无论如何操作, 都不能变为下一个m + 1的整倍
// 因此, m + 1的整倍出现的位置是固定的(包括0)
// 若先手不是m + 1的整倍, 他可以让后手成为m + 1的整倍
// 之后, 后手面临的都是m + 1的整倍, 即后手最先面临m
// 之后先手必胜, 反之同理, 巴巴博弈(doge)

string BashGame(int n, int m) {
    return n % (m + 1) != 0 ? "先手" : "后手";
}