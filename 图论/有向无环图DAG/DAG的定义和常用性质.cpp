// 有向无环图(DAG): 不包含任何有向环的有向图
// (自环是长度1的环, 自动排除; 重边/平行边是允许的)
// 平行边就是方向端点都相同的边

// 性质：

// 1:
// DAG的缩点图就是他本身

// 2:
// 入口x: 入度 = 0的点个数
// 出口y: 出度 = 0的点个数
// 一定存在x>=1 且 y>=1
// 让DAG图缩成一个SCC至少需要max(x, y)条边(该下界可达)
// 特例, 当n = 1时(此时x = y = 1, 但这只是必要条件), 答案 = 0

// 3:
// 若DAG图中的任意两点(u, v), 总是存在一条路径使得u抵达v或v抵达u
// 则他的拓扑排序过程中, 一定满足任何时刻队列的大小 <= 1
// 此时: 拓扑序唯一, 存在哈密顿路径(一条恰好经过图中每个顶点一次的路径)

// 4:
// 任意有向图中任意两点(u, v), 总是存在一条路径使得u抵达v或v抵达u
// 这样的图成为半连通图
// 半连通图缩点后形成的DAG图, 一定是一条链